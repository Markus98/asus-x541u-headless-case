"""Stamp measurements/*.json into cad/base.py between the BEGIN/END markers."""
import json, re
b = json.load(open("measurements/board_mm.json")); o = b["outline"]; f = json.load(open("measurements/fan_mm.json")); e = f["envelope"]
p = json.load(open("measurements/ports_mm.json")); od = json.load(open("measurements/odd_mounts_mm.json")); sd = json.load(open("measurements/ssd_mm.json")); pp = json.load(open("measurements/port_profiles_mm.json"))["ports"]
block = f"""# BEGIN board params (generated by tools/gen_params.py from measurements/*.json)
L = {b['L']}                       # port edge
W = {b['W']}                       # width
step_y = {o['audio end / step edge'][1]}                 # lower part Y extent
inner_x = {o['inner L corner'][0]}                # upper part X extent
holes = {json.dumps(b['holes'])}
fan_mounts = {json.dumps(f['mounts'])}
wifi_nub = ({f['wifi_nub'][0]}, {f['wifi_nub'][1]})      # WiFi card locating post, in line with M3
fan_boss_h = {json.dumps(f['boss_h'])}     # M2 and M3 boss heights above the floor (M1 is clamped under the board at H9)
fan_env = ({e['X_min']}, {e['X_max']}, {e['Y_min']}, {e['Y_max']})      # X_min, X_max, Y_min, Y_max
fan_center = ({f['impeller_center'][0]}, {f['impeller_center'][1]})
fan_impeller_d = {f['impeller_dia']}
port_x = {json.dumps(p['port_edge_X'])}      # connector X extents along the port edge
port_profiles = {json.dumps({k: dict(x=v['x'], z_top=v['z_top'], z_bottom=v['z_bottom'], face_w=v['face_w'], shape=v['shape'], **({'d': v['d']} if 'd' in v else {})) for k, v in pp.items()})}     # z relative to the PCB underside, from img1106
odd_mounts = {json.dumps(od['mounts'])}     # ODD board holes O1 and O7 in the board frame (O6 sits on H8)
odd_boss_h = {od['boss_h']}
ssd_x = ({sd['x_from']}, {sd['x_to']}); ssd_y = ({sd['y_far_end']}, {sd['y_connector_end']}); ssd_z_top = {sd['z_top']}     # SSD, bottom (hole side) up
ssd_holes = {json.dumps(sd['bottom_holes'])}     # SFF-8201 bottom holes, M3
# END board params"""
s = open("cad/base.py").read()
s = re.sub(r"# BEGIN board params.*?# END board params", block, s, flags=re.S)
open("cad/base.py", "w").write(s)
print(block)

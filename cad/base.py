def rect(xa, xb, ya, yb, za, zb):
    return Box(xb - xa, yb - ya, zb - za, align=(Align.MIN, Align.MIN, Align.MIN)).move(Location((xa, ya, za)))

def post(x, y, od, height, z0):
    return Cylinder(od / 2, height, align=(Align.CENTER, Align.CENTER, Align.MIN)).move(Location((x, y, z0)))

def coil_end(x, y, toward):
    """One end of the antenna cable coil: a half-ring wall (C) of coil_t, coil_r outside, coil_h tall, with a 45 degree lip at the top.
    toward = +1 bulges toward +Y, -1 toward -Y."""
    ri, ro, rl, h = coil_r - coil_t, coil_r, coil_r + coil_lip, coil_h
    prof = Plane.XZ * Polygon((ri, 0), (ro, 0), (ro, h - 2 * coil_lip), (rl, h - coil_lip), (rl, h), (ri, h), align=None)
    end = revolve(prof, axis=Axis.Z, revolution_arc=180)
    if end.center().Y * toward < 0: end = end.rotate(Axis.Z, 180)
    return end.move(Location((x, y, floor_t - 0.01)))

def grille_points():
    """Hex grid of grille hole centres inside the fan impeller circle (floor grille under the fan, lid grille above it)."""
    r_max = fan_impeller_d / 2 - grille_hole_d / 2
    dy = grille_pitch * math.sqrt(3) / 2
    pts = []
    for j in range(-8, 9):
        for i in range(-8, 9):
            px_ = fan_center[0] + i * grille_pitch + (grille_pitch / 2 if j % 2 else 0)
            py_ = fan_center[1] + j * dy
            if 8 < math.hypot(px_ - fan_center[0], py_ - fan_center[1]) <= r_max:
                pts.append((px_, py_))
    return pts

def grille(za, zb):
    """Grille holes through a plate between za and zb."""
    with BuildPart() as gr:
        with Locations(*[(px_, py_, za - 1) for px_, py_ in grille_points()]):
            Cylinder(grille_hole_d / 2, zb - za + 2, align=(Align.CENTER, Align.CENTER, Align.MIN))
    return gr.part

def port_cutter(p, wt):
    """Through-wall cutter for one connector: face shape plus port_margin, never below the floor top."""
    xa, xb = p["x"]; wd = xb - xa + 2 * port_margin
    zt = z_pcb + p["z_top"] + port_margin; zb = max(z_pcb + p["z_bottom"] - port_margin, floor_t)
    ht = zt - zb; xc, zc = (xa + xb) / 2, (zt + zb) / 2
    with BuildSketch() as sk:
        if p["shape"] == "rect": RectangleRounded(wd, ht, 0.8)
        elif p["shape"] == "rrect": RectangleRounded(wd, ht, 1.5)
        elif p["shape"] == "stadium": SlotOverall(wd, ht)
        elif p["shape"] == "circle": Circle(p.get("d", max(wd, ht)) / 2)      # given diameter (DC plug boot) or the face size
        elif p["shape"] == "dsub":                                   # D-sub shell: 10 degree sides, narrower at the bottom
            d = ht * math.tan(math.radians(10))
            Polygon((-wd / 2, ht / 2), (wd / 2, ht / 2), (wd / 2 - d, -ht / 2), (-wd / 2 + d, -ht / 2), align=None)
            fillet(sk.vertices(), 1.5)
        elif p["shape"] == "hdmi":                                   # lower corners chamfered
            c = 2.0
            Polygon((-wd / 2, ht / 2), (wd / 2, ht / 2), (wd / 2, -ht / 2 + c), (wd / 2 - c, -ht / 2), (-wd / 2 + c, -ht / 2), (-wd / 2, -ht / 2 + c), align=None)
            fillet(sk.vertices(), 0.6)
    solid = extrude(sk.sketch, amount=wt + 2)
    return solid.rotate(Axis.X, 90).move(Location((xc, y0 + 1, zc)))     # sketch y -> z, extruded along -y through the wall

def outline_box(za, zb, wt, chamfer_z=None):
    """Outer footprint with rounded corners; chamfer_z = za or zb chamfers that perimeter (case bottom, lid top)."""
    o = rect(x0 - wt, x1 + wt, y0 - wt, y1 + wt, za, zb)
    o = o.fillet(corner_r, o.edges().filter_by(Axis.Z))
    if chamfer_z is not None:
        o = o.chamfer(edge_chamfer, None, o.edges().group_by(Axis.Z)[0 if chamfer_z == za else -1])
    return o


def led_slit_cutters():
    """LED peek slit through the lid: a led_slit_w stadium slot, flared at 45 degrees on the inside (lid underside) by led_slit_flare."""
    yc = (led_y[0] + led_y[1]) / 2; ln = led_y[1] - led_y[0] + 2 * led_slit_margin
    def section(z, g):
        return Plane((led_slit_x, yc, z)) * SlotOverall(ln + 2 * g, led_slit_w + 2 * g, rotation=90)
    through = extrude(section(case_h - 1, 0), amount=lid_t + 2)
    flare = loft([section(case_h - 1, led_slit_flare + 1), section(case_h + led_slit_flare, 0)], ruled=True)
    return [through, flare]

def build_lid(skeleton=False):
    """skeleton=True: fit jig, the plate reduced to a perimeter band plus bars through the SSD holes, no chamfer."""
    plate = outline_box(case_h, case_h + lid_t, wall_t, chamfer_z=None if skeleton else case_h + lid_t)
    if skeleton:
        plate = plate - rect(x0 + jig_lid_band, x1 - jig_lid_band, y0 + jig_lid_band, y1 - jig_lid_band, case_h - 1, case_h + lid_t + 1)
        bars = [rect(x0 - 1, x1 + 1, Y - jig_lid_bar / 2, Y + jig_lid_bar / 2, case_h, case_h + lid_t) for X, Y in ssd_holes]
        bars += [rect(X - jig_lid_bar / 2, X + jig_lid_bar / 2, y0 - 1, y1 + 1, case_h, case_h + lid_t) for X, Y in ssd_holes]
        plate = plate.fuse(*bars)
    else:
        plate = plate - grille(case_h, case_h + lid_t)       # lid grille over the fan: the main intake on a shelf (floor grille blocked)
        plate = plate.cut(*led_slit_cutters())                # peek slit for the power and charger LEDs
    lip = rect(x0 + lip_clear, x1 - lip_clear, y0 + lip_clear, y1 - lip_clear, case_h - lip_h, case_h + 0.01)
    lip = lip - rect(x0 + lip_clear + lip_t, x1 - lip_clear - lip_t, y0 + lip_clear + lip_t, y1 - lip_clear - lip_t, case_h - lip_h - 1, case_h + 1)
    lip = lip.cut(*[post(X, Y, post_od + 2 * lip_clear, lip_h + 2, case_h - lip_h - 1) for X, Y in lid_posts])   # lip clears the posts
    lip = lip - rect(ssd_x[0] - 1, ssd_x[1] + 1, y0 - 1, y0 + lip_clear + lip_t + 0.5, case_h - lip_h - 1, case_h + 1)   # no lip where the SSD meets the port-edge wall
    lip = lip.fuse(*[post(X, Y, lid_boss_d, lip_h + 0.01, case_h - lip_h) for X, Y in lid_posts])               # bosses plug into the post counterbores
    with BuildPart() as lb:
        add(plate + lip)
        with Locations(*[(X, Y, case_h + lid_t) for X, Y in lid_posts]):
            CounterBoreHole(post_screw_d / 2, lid_cbore_d / 2, lid_cbore_depth)
        with Locations(*[(X, Y, case_h + lid_t) for X, Y in ssd_holes]):
            CounterBoreHole(ssd_hole_d / 2, lid_cbore_d / 2, lid_cbore_depth)
    return lb.part


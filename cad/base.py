def sd_funnel(wt):
    """SD slot as a rectangular funnel in the audio-end wall: a plate edge_clear from the board edge carries the slot with sd_flat of flat
    area around it, and from the plate's outer face the opening flares at sd_flare_deg per side in Y and up and down in Z to the outer wall
    face. The funnel is a solid block from the floor to just under the lid lip, so when the base prints on its floor nothing in it overhangs
    more than the flare angle (the downward flare stops sd_floor_margin above the floor top). Returns (block to fuse, pockets to cut)."""
    xa, xb = L + edge_clear, x1 + wt                       # plate inner face, outer wall face
    xp = xa + wt                                           # plate outer face, where the flare starts
    run = xb - xp
    f = run * math.tan(math.radians(sd_flare_deg))         # flare per side over the run
    w, h = sd_y[1] - sd_y[0], z_pcb_top - (floor_t + sd_z_from)
    yc, zc = (sd_y[0] + sd_y[1]) / 2, (floor_t + sd_z_from + z_pcb_top) / 2
    def section(x, gy, gz, r):
        """Rounded rectangle on the YZ plane at x: the slot grown by gy per side in Y and gz up and down."""
        return Plane((x, yc, zc), x_dir=(0, 1, 0), z_dir=(1, 0, 0)) * RectangleRounded(w + 2 * gy, h + 2 * gz, r)
    def block(x, hy, zt):
        """Plain rectangle on the YZ plane at x from the floor up to zt, half-width hy."""
        zb = floor_t - 0.01
        return Plane((x, yc, (zb + zt) / 2), x_dir=(0, 1, 0), z_dir=(1, 0, 0)) * Rectangle(2 * hy, zt - zb)
    py, pz = sd_flat
    t = wt / math.cos(math.radians(sd_flare_deg))          # side wall grown by this for wt across the sloped faces
    k = (xb + 1 - xp) / run                                # pocket extended 1 past the outer face for a clean cut
    r = sd_corner_r + min(py, pz)
    pocket = loft([section(xp, py, pz, r), section(xb + 1, py + f * k, pz + f * k, r)], ruled=True)
    pocket = pocket & rect(xp - 1, xb + 2, y0 - 50, y1 + 50, floor_t + sd_floor_margin, case_h + 1)
    slot = extrude(section(xa - 1, 0, 0, sd_corner_r), amount=wt + 2)
    zt, xo = case_h - lip_h - lip_clear, x1 + 0.5          # block top under the lid lip; block ends inside the main wall
    hy = w / 2 + py + t
    body = loft([block(xa, hy, zt), block(xp, hy, zt), block(xo, hy + f * (xo - xp) / run, zt)], ruled=True)
    return body, [pocket, slot]

def build(wt, skeleton=False):
    """Base with wall thickness wt. skeleton=True: fit jig, floor replaced by bars, lower walls."""
    wall_top = jig_wall_h if skeleton else case_h
    part = outline_box(0, wall_top, wt, chamfer_z=None if skeleton else 0) - rect(x0, x1, y0, y1, floor_t, wall_top + 1)
    adds, cuts = [], []            # batched: one fuse and one cut instead of one boolean per feature (keeps the build under the time limit)
    if skeleton:
        keep = [rect(x0 - 1, x1 + 1, Y - jig_bar_w / 2, Y + jig_bar_w / 2, -1, floor_t + 1) for X, Y, *_ in bosses + lid_posts]
        keep += [rect(X - jig_bar_w / 2, X + jig_bar_w / 2, y0 - 1, y1 + 1, -1, floor_t + 1) for X, Y, *_ in bosses + lid_posts]
        keep += [rect(cx - jig_bar_w / 2, cx + jig_bar_w / 2, y0 - 1, y1 + 1, -1, floor_t + 1) for cx in chan_x]
        keep.append(rect(L + edge_clear - 1, L + edge_clear + wt + 1, sd_y[0] - 12, sd_y[1] + 12, -1, floor_t + 1))   # floor under the SD funnel plate
        keep.append(rect(coil_x - jig_bar_w / 2, coil_x + jig_bar_w / 2, y0 - 1, y1 + 1, -1, floor_t + 1))             # bars under the coil ends
        keep += [rect(x0 - 1, x1 + 1, Y - jig_bar_w / 2, Y + jig_bar_w / 2, -1, floor_t + 1) for Y in coil_y]
        keep += [post(X, Y, od, floor_t + 2, -1) for X, Y, od, *_ in bosses] + [post(X, Y, post_od, floor_t + 2, -1) for X, Y in lid_posts]
        part = part - rect(x0, x1, y0, y1, -1, floor_t + 0.01).cut(*keep)
        for X, Y in lid_posts:                                    # full-thickness wall strips at the corners so the posts are embedded, not hanging
            xa, xb = (x0 - wall_t, x0 + 0.01) if X < (x0 + x1) / 2 else (x1 - 0.01, x1 + wall_t)
            ya, yb = (y0 - wall_t, y0 + 0.01) if Y < (y0 + y1) / 2 else (y1 - 0.01, y1 + wall_t)
            yl = (y0 - wall_t, y0 + jig_corner_pad) if Y < (y0 + y1) / 2 else (y1 - jig_corner_pad, y1 + wall_t)
            xl = (x0 - wall_t, x0 + jig_corner_pad) if X < (x0 + x1) / 2 else (x1 - jig_corner_pad, x1 + wall_t)
            adds += [rect(xa, xb, yl[0], yl[1], 0, case_h), rect(xl[0], xl[1], ya, yb, 0, case_h)]
    # wind channel walls under the board (floor to PCB underside)
    adds += [rect(cx - chan_t / 2, cx + chan_t / 2, chan_y[0], chan_y[1], floor_t - 0.01, z_pcb) for cx in chan_x]
    adds += [post(X, Y, od, h + 0.01, floor_t - 0.01) for X, Y, od, h, d in bosses]
    adds.append(post(*wifi_nub, wifi_nub_pin_d, wifi_nub_pin_h + 0.01, floor_t + fan_boss_h["M3"] + wifi_nub_h - 0.01))
    adds += [coil_end(coil_x, coil_y[0], -1), coil_end(coil_x, coil_y[1], +1)]      # antenna cable coil ends
    board_x = rect(-edge_clear, L + edge_clear, y0 - 1, y1 + 1, -1, case_h + 1)     # the board's X extent plus clearance: the posts are flattened there
    adds += [post(X, Y, post_od, case_h - floor_t + 0.01, floor_t - 0.01) - board_x for X, Y in lid_posts]    # lid screw posts, floor to wall top
    part = part.fuse(*adds)
    # screw pilots (grouped by depth) and the lid post insert holes below a lead-in counterbore, in one pass
    with BuildPart() as b:
        add(part)
        for depth in sorted({d for *_, d in bosses if d > 0}):
            with Locations(*[(X, Y, floor_t + h) for X, Y, od, h, d in bosses if d == depth]):
                Hole(pilot_d / 2, depth=depth)
        with Locations(*[(X, Y, case_h) for X, Y in lid_posts]):
            CounterBoreHole(post_insert_d / 2, post_cbore_d / 2, lip_h, depth=lip_h + post_insert_depth)
    part = b.part
    # port openings in the port-edge wall, following each connector face (profile photo), port_margin all round
    cuts += [port_cutter(p, wt) for p in port_profiles.values()]
    # SD slot window on the audio-end wall
    # SD slot: the wall steps in as a rectangular funnel so the slot sits at the board edge, reachable by a finger
    sd_shell, sd_pockets = sd_funnel(wt)
    part = part.fuse(sd_shell)
    cuts += sd_pockets
    if not skeleton:
        # vents: floor grille of round holes under the fan intake opening (hex grid inside the impeller circle)
        cuts.append(grille(0, floor_t))
    # vents, all in the port-edge wall: exhaust under the board between the channel walls, intake above the ports so the air
    # entering has to cross the board top to reach the fan
    cuts += vent_cutters(wt)
    return part.cut(*cuts)

def vent_cutters(wt):
    """Exhaust and intake slot cutters for the port-edge wall of thickness wt."""
    out = []
    xa, xb = chan_x[0] + 1, chan_x[1] - 1                   # exhaust: exhaust_slots wide slots across the channel
    w = (xb - xa - (exhaust_slots - 1) * vent_rib) / exhaust_slots
    out += [rect(xa + i * (w + vent_rib), xa + i * (w + vent_rib) + w, y0 - wt - 1, y0 + 1, *exhaust_z) for i in range(exhaust_slots)]
    x = intake_x[0]                                         # intake: vent_w wide slots
    while x + vent_w <= intake_x[1]:
        out.append(rect(x, x + vent_w, y0 - wt - 1, y0 + 1, *intake_z)); x += vent_w + vent_rib
    return out

